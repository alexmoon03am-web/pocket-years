INK='#264b44'
def icon(name, painter):
    im=Image.new('RGBA',(16,16));d=ImageDraw.Draw(im)
    def L(points,w=2): d.line(points,fill=INK,width=w)
    def P(points): d.polygon(points,fill=INK)
    def R(x1,y1,x2,y2):d.rectangle((x1,y1,x2,y2),fill=INK)
    def E(box,w=2):d.ellipse(box,outline=INK,width=w)
    painter(L,P,R,E);im.save(OUT/(name+'.png'))
